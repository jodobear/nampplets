"use strict";

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const policy = require("../trusted-shell-policy.js");
const artifactPolicy = require("../trusted-shell-artifact-policy.js");

const root = path.join(__dirname, "..");
const scriptNames = Object.freeze([
  "trusted-shell-policy.js",
  "trusted-shell-prelude-domains.js",
  "trusted-shell.js",
  "trusted-shell-artifact-policy.js",
  "trusted-shell-surface-host.js",
  "trusted-shell-embedding-contract.js",
  "trusted-shell-embedding.js"
]);

function inlineScript(name) {
  const source = fs.readFileSync(path.join(root, name), "utf8");
  return source.replace(/<\/script/gi, "<\\/script");
}

function renderBootstrap(input) {
  const normalized = artifactPolicy.normalizeArtifactPolicy(input);
  const elevated = artifactPolicy.constructorInput(normalized);
  const serialized = elevated === null ? null : JSON.stringify(elevated)
    .replace(/&/g, "\\u0026")
    .replace(/</g, "\\u003c")
    .replace(/>/g, "\\u003e")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
  const options = elevated === null
    ? ""
    : `, { artifactPolicy: ${serialized} }`;
  return "  <script data-source=\"trusted-shell-bootstrap\">\n" +
    "if (window.parent !== window) {\n" +
    `  NMPTrustedShellEmbedding.createEmbeddingBridge(window${options});\n` +
    "}\n" +
    "  </script>";
}

function renderEmbeddedShell(options = {}) {
  const fields = Object.keys(options);
  if (fields.some((field) => field !== "artifactPolicy")) {
    throw new TypeError("unsupported embedded trusted-shell option");
  }
  const scripts = scriptNames
    .map((name) =>
      `  <script data-source="${name}">\n${inlineScript(name)}\n  </script>`
    )
    .join("\n");
  const bootstrap = renderBootstrap(options.artifactPolicy);
  const style = fs.readFileSync(path.join(root, "trusted-shell.css"), "utf8");
  if (/<\/style/i.test(style)) {
    throw new Error("trusted-shell.css cannot be safely inlined");
  }
  return `<!doctype html>
<!-- Generated by scripts/render-trusted-shell-embedded.js; immutable outer-shell bytes. -->
<html lang="en">
<head>
  <meta
    http-equiv="Content-Security-Policy"
    content="${policy.outerPolicyContent()}"
  >
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>NMP Native Runtime embedded trusted shell</title>
  <style>${style}</style>
</head>
<body>
  <main id="surface" aria-label="Napplet surface">
    <div id="loading" role="status">Preparing verified napplet…</div>
  </main>
${scripts}
${bootstrap}
</body>
</html>
`;
}

function writeEmbeddedShell() {
  const output = renderEmbeddedShell();
  const outputPath = path.join(root, "trusted-shell-embedded.html");
  fs.writeFileSync(outputPath, output);
  const digest = crypto.createHash("sha256").update(output).digest("hex");
  fs.writeFileSync(
    path.join(root, "trusted-shell-embedded.sha256"),
    `${digest}  trusted-shell-embedded.html\n`
  );
}

function checkEmbeddedShell() {
  const output = renderEmbeddedShell();
  const digest = crypto.createHash("sha256").update(output).digest("hex");
  const recordedOutput = fs.readFileSync(
    path.join(root, "trusted-shell-embedded.html"),
    "utf8"
  );
  const recordedDigest = fs.readFileSync(
    path.join(root, "trusted-shell-embedded.sha256"),
    "utf8"
  );
  if (recordedOutput !== output) {
    throw new Error("trusted-shell-embedded.html is stale");
  }
  if (recordedDigest !== `${digest}  trusted-shell-embedded.html\n`) {
    throw new Error("trusted-shell-embedded.sha256 is stale");
  }
}

if (require.main === module) {
  if (process.argv.length === 2) writeEmbeddedShell();
  else if (process.argv.length === 3 && process.argv[2] === "--check") {
    checkEmbeddedShell();
  } else {
    throw new Error("usage: render-trusted-shell-embedded.js [--check]");
  }
}

module.exports = Object.freeze({
  checkEmbeddedShell,
  renderBootstrap,
  renderEmbeddedShell,
  scriptNames
});
